export type AppStoreConfig = {
  dir: string;
  maxFileBytes: number;
  maxUserBytes: number;
  maxApps: number;
  allowHttp: boolean;
  allowPrivate: boolean;
};

export const DEFAULT_APP_STORE: AppStoreConfig = {
  dir: '/data/apps', maxFileBytes: 200 * 1024 * 1024, maxUserBytes: 1024 * 1024 * 1024, maxApps: 50,
  allowHttp: false, allowPrivate: false,
};

export function loadAppStoreConfig(env: NodeJS.ProcessEnv): AppStoreConfig {
  const mb = (name: string, fallback: number, max: number): number => {
    const raw = env[name];
    if (raw === undefined || raw === '') return fallback * 1024 * 1024;
    const value = Number(raw);
    if (!Number.isInteger(value) || value < 1 || value > max) throw new Error(`${name} must be an integer from 1 to ${max}`);
    return value * 1024 * 1024;
  };
  const flag = (name: string): boolean => {
    const raw = env[name];
    if (raw === undefined || raw === '' || raw === 'false') return false;
    if (raw === 'true') return true;
    throw new Error(`${name} must be true or false`);
  };
  const dir = env.APP_STORE_DIR || DEFAULT_APP_STORE.dir;
  if (!path.isAbsolute(dir) && !path.posix.isAbsolute(dir)) throw new Error('APP_STORE_DIR must be an absolute path');
  return {
    dir,
    maxFileBytes: mb('APP_STORE_MAX_FILE_MB', DEFAULT_APP_STORE.maxFileBytes / 1048576, 1024),
    maxUserBytes: mb('APP_STORE_MAX_MB_PER_USER', DEFAULT_APP_STORE.maxUserBytes / 1048576, 102_400),
    maxApps: DEFAULT_APP_STORE.maxApps,
    allowHttp: flag('APP_ALLOW_HTTP'),
    allowPrivate: flag('APP_ALLOW_PRIVATE'),
  };
}

// ---- Paths: only ids generated by the server ever reach the file system. ----

export function userDir(root: string, userId: string): string {
  if (!isUuid(userId)) throw new Error('Invalid user id');
  return path.join(root, userId.toLowerCase());
}

export function appFilePath(root: string, userId: string, appId: string): string {
  if (!isUuid(appId)) throw new Error('Invalid app id');
  const full = path.resolve(userDir(root, userId), `${appId.toLowerCase()}.apk`);
  if (!full.startsWith(path.resolve(root) + path.sep)) throw new Error('Path escapes the store');
  return full;
}

// ---- ZIP and binary AndroidManifest.xml ----

const MAX_MANIFEST_BYTES = 16 * 1024 * 1024;

export const hasZipMagic = (head: Buffer): boolean =>
  head.length >= 4 && head[0] === 0x50 && head[1] === 0x4b && head[2] === 0x03 && head[3] === 0x04;

type ZipEntry = { name: string; method: number; compressedSize: number; size: number; offset: number };

// Reads the central directory from the end of the file; never loads the whole archive.
async function readCentralDirectory(file: string): Promise<{ entries: ZipEntry[]; fd: Awaited<ReturnType<typeof open>> }> {
  const fd = await open(file, 'r');
  try {
    const { size } = await fd.stat();
    const tailLength = Math.min(size, 65_557);
    const tail = Buffer.alloc(tailLength);
    await fd.read(tail, 0, tailLength, size - tailLength);
    let eocd = -1;
    for (let i = tailLength - 22; i >= 0; i--) {
      if (tail.readUInt32LE(i) === 0x06054b50) { eocd = i; break; }
    }
    if (eocd < 0) throw new Error('No ZIP directory');
    const count = tail.readUInt16LE(eocd + 10);
    const dirSize = tail.readUInt32LE(eocd + 12);
    const dirOffset = tail.readUInt32LE(eocd + 16);
    if (count === 0xffff || dirOffset === 0xffffffff || dirSize > 16 * 1024 * 1024 || dirOffset + dirSize > size) throw new Error('Unsupported ZIP');
    const dir = Buffer.alloc(dirSize);
    await fd.read(dir, 0, dirSize, dirOffset);
    const entries: ZipEntry[] = [];
    let pos = 0;
    for (let n = 0; n < count && pos + 46 <= dir.length; n++) {
      if (dir.readUInt32LE(pos) !== 0x02014b50) throw new Error('Corrupt ZIP directory');
      const nameLength = dir.readUInt16LE(pos + 28);
      const extraLength = dir.readUInt16LE(pos + 30);
      const commentLength = dir.readUInt16LE(pos + 32);
      if (pos + 46 + nameLength > dir.length) throw new Error('Corrupt ZIP directory');
      entries.push({
        name: dir.toString('utf8', pos + 46, pos + 46 + nameLength), method: dir.readUInt16LE(pos + 10),
        compressedSize: dir.readUInt32LE(pos + 20), size: dir.readUInt32LE(pos + 24), offset: dir.readUInt32LE(pos + 42),
      });
      pos += 46 + nameLength + extraLength + commentLength;
    }
    return { entries, fd };
  } catch (error) {
    await fd.close();
    throw error;
  }
}

async function readEntry(fd: Awaited<ReturnType<typeof open>>, entry: ZipEntry): Promise<Buffer> {
  if (entry.size > MAX_MANIFEST_BYTES || entry.compressedSize > MAX_MANIFEST_BYTES) throw new Error('Manifest too large');
  const local = Buffer.alloc(30);
  await fd.read(local, 0, 30, entry.offset);
  if (local.readUInt32LE(0) !== 0x04034b50) throw new Error('Corrupt ZIP entry');
  const start = entry.offset + 30 + local.readUInt16LE(26) + local.readUInt16LE(28);
  const raw = Buffer.alloc(entry.compressedSize);
  await fd.read(raw, 0, raw.length, start);
  if (entry.method === 0) return raw;
  if (entry.method === 8) return inflateRawSync(raw, { maxOutputLength: MAX_MANIFEST_BYTES });
  throw new Error('Unsupported compression');
}

export type ApkInfo = { packageName?: string; versionName?: string };

// Resolves to null when the file is not a ZIP with AndroidManifest.xml; manifest parse problems only drop the fields.
export async function inspectApk(file: string): Promise<ApkInfo | null> {
  let directory;
  try { directory = await readCentralDirectory(file); } catch { return null; }
  try {
    const entry = directory.entries.find(item => item.name === 'AndroidManifest.xml');
    if (!entry) return null;
    try { return parseManifest(await readEntry(directory.fd, entry)); } catch { return {}; }
  } finally {
    await directory.fd.close();
  }
}

export async function inspectApplication(file: string, name: string): Promise<ApkInfo | null> {
  if (/\.apk$/i.test(name)) return inspectApk(file);
  if (!/\.(apks|zip)$/i.test(name)) return null;
  try { await inspectApkSet(file, /\.apks$/i.test(name)); return {}; } catch { return null; }
}

// Minimal AXML reader: string pool plus the attributes of the root <manifest> element.
export function parseManifest(buffer: Buffer): ApkInfo {
  if (buffer.length < 8 || buffer.readUInt16LE(0) !== 0x0003) throw new Error('Not binary XML');
  let pool: string[] = [];
  let pos = buffer.readUInt16LE(2);
  const info: ApkInfo = {};
  while (pos + 8 <= buffer.length) {
    const type = buffer.readUInt16LE(pos);
    const headerSize = buffer.readUInt16LE(pos + 2);
    const size = buffer.readUInt32LE(pos + 4);
    if (size < 8 || pos + size > buffer.length) throw new Error('Corrupt chunk');
    if (type === 0x0001) pool = readStringPool(buffer.subarray(pos, pos + size));
    else if (type === 0x0102) {
      const base = pos + 16;
      const nameIndex = buffer.readUInt32LE(base + 4);
      if (pool[nameIndex] !== 'manifest') throw new Error('Unexpected root element');
      const attrStart = base + buffer.readUInt16LE(base + 8);
      const attrSize = buffer.readUInt16LE(base + 10);
      const attrCount = buffer.readUInt16LE(base + 12);
      if (attrSize < 20) throw new Error('Corrupt attributes');
      for (let i = 0; i < attrCount && attrStart + (i + 1) * attrSize <= pos + size; i++) {
        const at = attrStart + i * attrSize;
        const name = pool[buffer.readUInt32LE(at + 4)];
        const rawIndex = buffer.readUInt32LE(at + 8);
        const valueType = buffer.readUInt8(at + 15);
        const data = buffer.readUInt32LE(at + 16);
        const text = rawIndex !== 0xffffffff ? pool[rawIndex] : valueType === 0x03 ? pool[data] : undefined;
        if (name === 'package' && text) info.packageName = text.slice(0, 255);
        if (name === 'versionName' && text) info.versionName = text.slice(0, 100);
      }
      return info;
    }
    pos += Math.max(size, headerSize);
  }
  throw new Error('No manifest element');
}

function readStringPool(chunk: Buffer): string[] {
  const count = chunk.readUInt32LE(8);
  const flags = chunk.readUInt32LE(16);
  const stringsStart = chunk.readUInt32LE(20);
  const headerSize = chunk.readUInt16LE(2);
  if (count > 200_000 || headerSize + count * 4 > chunk.length) throw new Error('Corrupt string pool');
  const utf8 = (flags & 0x100) !== 0;
  const strings: string[] = [];
  for (let i = 0; i < count; i++) {
    let at = stringsStart + chunk.readUInt32LE(headerSize + i * 4);
    if (at >= chunk.length) { strings.push(''); continue; }
    if (utf8) {
      const readLength = (): number => {
        let value = chunk.readUInt8(at++);
        if (value & 0x80) value = ((value & 0x7f) << 8) | chunk.readUInt8(at++);
        return value;
      };
      readLength();
      const bytes = readLength();
      strings.push(chunk.toString('utf8', at, Math.min(at + bytes, chunk.length)));
    } else {
      let length = chunk.readUInt16LE(at);
      at += 2;
      if (length & 0x8000) { length = ((length & 0x7fff) << 16) | chunk.readUInt16LE(at); at += 2; }
      strings.push(chunk.toString('utf16le', at, Math.min(at + length * 2, chunk.length)));
    }
  }
  return strings;
}

export async function sha256File(file: string): Promise<string> {
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(file)) hash.update(chunk as Buffer);
  return hash.digest('hex');
}

export async function readHead(file: string, length = 4): Promise<Buffer> {
  const fd = await open(file, 'r');
  try {
    const buffer = Buffer.alloc(length);
    const { bytesRead } = await fd.read(buffer, 0, length, 0);
    return buffer.subarray(0, bytesRead);
  } finally { await fd.close(); }
}

// ---- Outbound URL safety ----

const v4 = (text: string): number[] | null => {
  const parts = text.split('.').map(Number);
  return parts.length === 4 && parts.every(n => Number.isInteger(n) && n >= 0 && n <= 255) ? parts : null;
};

function isPrivateV4(p: number[]): boolean {
  const [a, b, c] = p as [number, number, number, number];
  return a === 0 || a === 10 || a === 127 || a >= 224 ||
    (a === 100 && b >= 64 && b <= 127) || (a === 169 && b === 254) || (a === 172 && b >= 16 && b <= 31) ||
    (a === 192 && b === 168) || (a === 192 && b === 0 && (c === 0 || c === 2)) || (a === 198 && (b === 18 || b === 19)) ||
    (a === 198 && b === 51 && c === 100) || (a === 203 && b === 0 && c === 113);
}

function expandV6(address: string): number[] | null {
  let text = address.split('%')[0]!.toLowerCase();
  const tail = /(\d+\.\d+\.\d+\.\d+)$/.exec(text);
  if (tail) {
    const parts = v4(tail[1]!);
    if (!parts) return null;
    text = text.slice(0, -tail[1]!.length) + ((parts[0]! << 8) | parts[1]!).toString(16) + ':' + ((parts[2]! << 8) | parts[3]!).toString(16);
  }
  const halves = text.split('::');
  if (halves.length > 2) return null;
  const head = halves[0] ? halves[0].split(':') : [];
  const rest = halves.length === 2 && halves[1] ? halves[1].split(':') : [];
  const fill = halves.length === 2 ? 8 - head.length - rest.length : 0;
  if (fill < 0 || (halves.length === 1 && head.length !== 8)) return null;
  const groups = [...head, ...Array<string>(fill).fill('0'), ...rest].map(g => parseInt(g, 16));
  return groups.length === 8 && groups.every(g => Number.isInteger(g) && g >= 0 && g <= 0xffff) ? groups : null;
}

// True for loopback, private, link-local, multicast, reserved and other non-public addresses. Unparseable input counts as private.
export function isPrivateAddress(address: string): boolean {
  const family = net.isIP(address);
  if (family === 4) { const parts = v4(address); return !parts || isPrivateV4(parts); }
  if (family !== 6) return true;
  const g = expandV6(address);
  if (!g) return true;
  const embedded = (hi: number, lo: number): number[] => [hi >> 8, hi & 255, lo >> 8, lo & 255];
  if (g.slice(0, 5).every(x => x === 0) && (g[5] === 0xffff || g[5] === 0)) {
    if (g[5] === 0 && g[6] === 0 && g[7]! <= 1) return true; // :: and ::1
    return isPrivateV4(embedded(g[6]!, g[7]!)); // IPv4-mapped / compatible
  }
  if (g[0] === 0x64 && g[1] === 0xff9b && g.slice(2, 6).every(x => x === 0)) return isPrivateV4(embedded(g[6]!, g[7]!)); // NAT64
  if (g[0] === 0x2002) return isPrivateV4(embedded(g[1]!, g[2]!)); // 6to4
  return (g[0]! & 0xfe00) === 0xfc00 || (g[0]! & 0xffc0) === 0xfe80 || (g[0]! & 0xff00) === 0xff00 ||
    (g[0] === 0x2001 && g[1] === 0x0db8) || g[0] === 0x100 && g[1] === 0;
}

export class DownloadError extends Error {
  constructor(public readonly code: string, message: string) { super(message); }
}

export function parseDownloadUrl(input: unknown, options: Pick<AppStoreConfig, 'allowHttp' | 'allowPrivate'>): URL {
  if (typeof input !== 'string' || input.length === 0 || input.length > 2048) throw new DownloadError('invalid_url', 'Enter a valid https:// link');
  let url: URL;
  try { url = new URL(input.trim()); } catch { throw new DownloadError('invalid_url', 'Enter a valid https:// link'); }
  if (url.protocol !== 'https:' && !(options.allowHttp && url.protocol === 'http:')) {
    throw new DownloadError('url_not_https', 'Only https:// links are allowed');
  }
  if (url.username || url.password) throw new DownloadError('url_credentials', 'Links with credentials are not supported; use a signed URL');
  const host = url.hostname.replace(/^\[|\]$/g, '');
  if (!host) throw new DownloadError('invalid_url', 'Enter a valid https:// link');
  if (!options.allowPrivate && net.isIP(host) && isPrivateAddress(host)) throw new DownloadError('url_private', 'This address is not allowed');
  return url;
}

// Host name only, safe for audit records (no path, no query).
export const urlHostLabel = (url: URL): string => url.hostname.replace(/[^A-Za-z0-9.-]/g, '').slice(0, 100);

// DNS lookup that rejects non-public results, so the connection goes to an address that was checked.
function guardedLookup(allowPrivate: boolean) {
  return (hostname: string, options: dns.LookupOptions, callback: (...args: unknown[]) => void): void => {
    dns.lookup(hostname, { ...options, all: true }, (error, addresses) => {
      if (error) { callback(error); return; }
      const list = addresses as dns.LookupAddress[];
      if (!allowPrivate && list.some(item => isPrivateAddress(item.address))) {
        callback(new DownloadError('url_private', 'This address is not allowed')); return;
      }
      if (options.all) callback(null, list); else callback(null, list[0]!.address, list[0]!.family);
    });
  };
}

const MAX_REDIRECTS = 3;

// Downloads to `destination`; the partial file is removed on any failure.
export async function downloadToFile(rawUrl: string, destination: string,
  options: Pick<AppStoreConfig, 'allowHttp' | 'allowPrivate' | 'maxFileBytes'>, timeoutMs = 60_000): Promise<{ size: number; url: URL }> {
  const deadline = Date.now() + timeoutMs;
  let url = parseDownloadUrl(rawUrl, options);
  try {
    for (let hop = 0; hop <= MAX_REDIRECTS; hop++) {
      const outcome = await fetchOnce(url, destination, options, Math.max(1, deadline - Date.now()));
      if (outcome.redirect) {
        if (hop === MAX_REDIRECTS) throw new DownloadError('too_many_redirects', 'Too many redirects');
        url = parseDownloadUrl(new URL(outcome.redirect, url).toString(), options);
        continue;
      }
      return { size: outcome.size, url };
    }
    throw new DownloadError('too_many_redirects', 'Too many redirects');
  } catch (error) {
    await rm(destination, { force: true });
    throw error;
  }
}

function fetchOnce(url: URL, destination: string, options: Pick<AppStoreConfig, 'allowPrivate' | 'maxFileBytes'>,
  timeoutMs: number): Promise<{ size: number; redirect?: string }> {
  return new Promise((resolve, reject) => {
    const transport = url.protocol === 'https:' ? https : http;
    let settled = false;
    let out: ReturnType<typeof createWriteStream> | undefined;
    const finish = (error: Error | null, value?: { size: number; redirect?: string }) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      if (error) { request.destroy(); out?.destroy(); reject(error); } else resolve(value!);
    };
    const request = transport.request(url, {
      method: 'GET', lookup: guardedLookup(options.allowPrivate) as never, agent: false,
      headers: { 'User-Agent': 'remote-device-farm', Accept: '*/*', 'Accept-Encoding': 'identity' },
    }, response => {
      const status = response.statusCode || 0;
      if ([301, 302, 303, 307, 308].includes(status)) {
        const location = response.headers.location;
        response.resume();
        if (!location) finish(new DownloadError('download_failed', 'Redirect without location'));
        else finish(null, { size: 0, redirect: location });
        return;
      }
      if (status !== 200) { response.resume(); finish(new DownloadError('download_failed', `The server answered ${status}`)); return; }
      const declared = Number(response.headers['content-length']);
      if (Number.isFinite(declared) && declared > options.maxFileBytes) {
        response.resume(); finish(new DownloadError('app_too_large', 'File is too large')); return;
      }
      let size = 0;
      out = createWriteStream(destination, { flags: 'w', mode: 0o600 });
      out.on('error', error => finish(error));
      out.on('finish', () => finish(null, { size }));
      response.on('data', (chunk: Buffer) => {
        size += chunk.length;
        if (size > options.maxFileBytes) finish(new DownloadError('app_too_large', 'File is too large'));
      });
      response.on('error', error => finish(error));
      response.on('aborted', () => finish(new DownloadError('download_failed', 'Download interrupted')));
      response.pipe(out);
    });
    const timer = setTimeout(() => finish(new DownloadError('download_timeout', 'Download took too long')), timeoutMs);
    request.on('error', error => finish(error instanceof DownloadError ? error : new DownloadError('download_failed', 'Could not download the file')));
    request.end();
  });
}

export async function ensureUserDir(root: string, userId: string): Promise<string> {
  const dir = userDir(root, userId);
  await mkdir(dir, { recursive: true, mode: 0o700 });
  return dir;
}

export async function fileSize(file: string): Promise<number> { return (await stat(file)).size; }
